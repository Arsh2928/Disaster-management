            <h3>Earthquakes</h3>
            <h4>Before an Earthquake:</h4>
            <ul>
                <li>Secure heavy furniture and appliances to walls</li>
                <li>Practice "Drop, Cover, and Hold On" drills</li>
                <li>Identify safe spots in each room (under sturdy furniture, against inside walls)</li>
                <li>Prepare an emergency kit with food, water, and supplies for several days</li>
            </ul>
            
            <h4>During an Earthquake:</h4>
            <ul>
                <li>Drop to your hands and knees to prevent being knocked down</li>
                <li>Cover your head and neck with your arms</li>
                <li>Hold on to any sturdy shelter until shaking stops</li>
                <li>If indoors, stay there; avoid doorways and windows</li>
                <li>If outdoors, move to an open area away from buildings, trees, and power lines</li>
            </ul>
            
            <h4>After an Earthquake:</h4>
            <ul>
                <li>Check yourself and others for injuries</li>
                <li>Be prepared for aftershocks</li>
                <li>Check for gas leaks and electrical damage</li>
                <li>Listen to emergency broadcasts for information</li>
            </ul>
        </div>
