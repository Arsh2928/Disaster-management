        <div id="flood" class="knowledge-section">
            <h3>Flood</h3>
            <h4>Before a Flood:</h4>
            <ul>
                <li>Know your area's flood risk and evacuation routes</li>
                <li>Elevate electrical appliances and utilities (e.g., HVAC, water heater)</li>
                <li>Install sump pumps with battery backup</li>
                <li>Prepare sandbags or barriers if flooding is imminent</li>
                <li>Keep important documents in waterproof containers</li>
            </ul>

            <h4>During a Flood:</h4>
            <ul>
                <li>Move to higher ground immediately; avoid walking/driving through floodwaters</li>
                <li>Do not enter flooded basements or rooms with electrical outlets</li>
                <li>If trapped, go to the highest level of your home (but avoid closed attics)</li>
                <li>Turn off electricity and gas if instructed</li>
                <li>Listen to emergency alerts (NOAA Weather Radio or local news)</li>
            </ul>

            <h4>After a Flood:</h4>
            <ul>
                <li>Avoid returning home until authorities declare it safe</li>
                <li>Watch for downed power lines and structural damage</li>
                <li>Discard contaminated food and water</li>
                <li>Wear protective gear during cleanup (boots, gloves, masks)</li>
                <li>Document damage for insurance claims</li>
            </ul>
</div>
        <br>
        <div id="hurricane" class="knowledge-section">
            <h3>Hurricanes</h3>
            <!-- Similar structure for hurricane information -->
            <h4>Before a Hurricane:</h4>
            <ul>
                <li>Reinforce windows with storm shutters or plywood</li>
                <li>Secure outdoor furniture and trim trees near your home</li>
                <li>Stock emergency supplies (food, water, batteries, medications)</li>
                <li>Know evacuation routes and shelter locations</li>
                <li>Charge phones and backup power banks</li>
            </ul>

            <h4>During a Hurricane:</h4>
            <ul>
                <li>Stay indoors away from windows and glass doors</li>
                <li>Take shelter in a small, windowless interior room (e.g., closet, bathroom)</li>
                <li>Use mattresses or heavy blankets for added protection</li>
                <li>Do not go outside during the "eye" of the storm—winds will return</li>
                <li>Monitor updates via battery-powered radio</li>
            </ul>

            <h4>After a Hurricane:</h4>
            <ul>
                <li>Wait for official confirmation that it's safe to go outside</li>
                <li>Avoid floodwaters and downed power lines</li>
                <li>Check for gas leaks and water damage</li>
                <li>Use flashlights (not candles) to prevent fires</li>
                <li>Contact family/friends via text (calls may overload networks)</li>
            </ul>
</div>
        
